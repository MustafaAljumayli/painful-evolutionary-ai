#!/usr/bin/env bash
# Makes the paper readable by every agent, using poppler from the project
# environment (environment.yml).
#
#   ./scripts/paper.sh text      regenerate docs/Pain_Axis.txt from the PDF
#   ./scripts/paper.sh check     exit 1 if the text is missing or out of date
#   ./scripts/paper.sh page 12   render page 12 to a PNG and print its path,
#                                for a figure or table the text garbles
#
# Agents read docs/Pain_Axis.txt and cite it as docs/Pain_Axis.txt:<line>.
# Regenerate it only when the PDF changes, because line numbers can move.
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"
. scripts/env.sh
if ! BIN="$(find_env_bin)"; then
  env_missing_message
  exit 1
fi

PDF="docs/Pain_Axis.pdf"
TXT="docs/Pain_Axis.txt"

pdf_sha() {
  "$BIN/python" -c 'import hashlib, sys; print(hashlib.sha256(open(sys.argv[1], "rb").read()).hexdigest())' "$PDF"
}

case "${1:-}" in
  text)
    version="$("$BIN/pdftotext" -v 2>&1 | head -n 1)"
    {
      echo "# Text of $PDF. Generated by ./scripts/paper.sh text ($version, -layout). Do not edit."
      echo "# PDF sha256: $(pdf_sha)"
      echo "# Cite as $TXT:<line>. A form-feed character marks each page break."
      "$BIN/pdftotext" -layout "$PDF" - 2>/dev/null
    } > "$TXT"
    echo "wrote $TXT ($(wc -l < "$TXT" | tr -d ' ') lines)"
    ;;
  check)
    if [ ! -f "$TXT" ]; then
      echo "$TXT is missing. Run: ./scripts/paper.sh text"
      exit 1
    fi
    if ! grep -q "^# PDF sha256: $(pdf_sha)$" "$TXT"; then
      echo "$TXT does not match $PDF. Run: ./scripts/paper.sh text"
      exit 1
    fi
    ;;
  page)
    page="${2:?usage: ./scripts/paper.sh page <number>}"
    out="${TMPDIR:-/tmp}/pain_axis_page_${page}"
    "$BIN/pdftoppm" -png -r 100 -f "$page" -l "$page" -singlefile "$PDF" "$out" 2>/dev/null
    echo "$out.png"
    ;;
  *)
    echo "usage: ./scripts/paper.sh text | check | page <number>"
    exit 2
    ;;
esac
